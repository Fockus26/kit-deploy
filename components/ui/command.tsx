"use client";

import { Command as CommandPrimitive } from "cmdk";
import { Search } from "lucide-react";
import type * as React from "react";
import { cn } from "@/lib/utils";

// shadcn/ui Command (new-york, cmdk), on kit-deploy's tokens: items like SelectItem (control
// height, raised when highlighted). cmdk gives the input role=combobox and the list
// role=listbox with role=option items, and moves the highlight with the arrows.

function Command({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive>) {
  return (
    <CommandPrimitive
      data-slot="command"
      className={cn(
        "flex h-full w-full flex-col overflow-hidden rounded-md bg-card text-card-foreground",
        className,
      )}
      {...props}
    />
  );
}

function CommandInput({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive.Input>) {
  return (
    <div
      data-slot="command-input-wrapper"
      className="flex items-center gap-2 border-border border-b-2 px-2 focus-within:border-ring"
    >
      <Search
        aria-hidden="true"
        className="size-4 shrink-0 text-muted-foreground"
      />
      <CommandPrimitive.Input
        data-slot="command-input"
        className={cn(
          "flex min-h-control w-full min-w-0 bg-transparent py-2 text-input-touch text-foreground outline-none placeholder:text-muted-foreground disabled:cursor-not-allowed disabled:text-disabled md:text-body",
          className,
        )}
        {...props}
      />
    </div>
  );
}

